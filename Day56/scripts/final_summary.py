"""Build docs/FINAL_EVALUATION.md from the stored evaluation and simulation files - every number in the document comes from a file in data/.

    python -m scripts.final_summary
"""
import json

from config import settings

EVAL = settings.data_dir / "eval"
SIM = settings.data_dir / "simulation"


def load(path):
    return json.loads(path.read_text(encoding="utf8"))


def pct(x) -> str:
    return f"{x:.1%}"


def build() -> str:
    runs = {v: load(EVAL / f"full_{v}.json") for v in ("v1", "v2", "v3", "v4")}
    modes = load(EVAL / "modes_final.json")
    sim = load(SIM / "week3_analysis.json")
    final = runs["v4"]
    v1_ids = {r["case_id"] for r in runs["v1"]["rows"]}
    same_cases = [r for r in final["rows"] if r["case_id"] in v1_ids]
    L = ["# Final evaluation summary (generated - run `python -m scripts.final_summary`)", "",
         f"Agent version `{final['summary']['agent_version']}`. Every number below is read from `data/eval/*.json` or `data/simulation/week3_analysis.json`.", "",
         "## 1. History: the evaluation set grew, so read the columns carefully", "",
         "| Run | Cases | Baseline pass | AI (graph) pass | AI unsafe errors | AI cost (USD) |", "|---|---:|---:|---:|---:|---:|"]
    for v, r in runs.items():
        s = r["summary"]
        L.append(f"| {v} | {len(r['rows'])} | {pct(s['baseline']['pass_rate'])} | {pct(s['ai']['pass_rate'])} | {s['ai']['errors'].get('unsafe_error', 0)} | {s['ai']['total_cost_usd']} |")
    L += ["", "The baseline number *falls* from v2 to v3 because harder cases were added, not because the baseline got worse.",
          f"Like-for-like: on the {len(same_cases)} cases that exist in v1, the final agent passes "
          f"{sum(r['ai_pass'] for r in same_cases)}/{len(same_cases)} and the rules-only baseline {sum(r['baseline_pass'] for r in same_cases)}/{len(same_cases)}.", "",
         "**Caveat:** the rules were tuned on this set. The 100% is a regression guard, not an estimate of performance on unseen traffic; the hold-out cases (8) were written after the fixes by the same author.", "",
         "## 2. Final run (v4, 45 cases, live model)", "", "| Metric | Rules only | Full agent |", "|---|---:|---:|"]
    b, a = final["summary"]["baseline"], final["summary"]["ai"]
    for label, key in (("case pass rate", "pass_rate"), ("action accuracy", "action_accuracy"), ("route accuracy", "route_accuracy"),
                       ("provider accuracy", "provider_accuracy"), ("explanation score (0-10)", "explanation_avg_score"),
                       ("latency p50 (ms)", "latency_p50_ms"), ("cost (USD)", "total_cost_usd")):
        L.append(f"| {label} | {b[key]} | {a[key]} |")
    L += [f"| unsafe errors | {b['errors'].get('unsafe_error', 0)} | {a['errors'].get('unsafe_error', 0)} |",
          f"| over-cautious errors | {b['errors'].get('over_cautious', 0)} | {a['errors'].get('over_cautious', 0)} |", "",
          "Pass rate per category (full agent): " + ", ".join(f"{k} {pct(v)}" for k, v in a["by_category"].items()) + ".", "",
          "Rules-only failures by kind: all are `unsafe_error` (too permissive) - the baseline never over-blocks, it lets policy, unknown-country and pattern cases through.", "",
          "## 3. Which layer earns the result? (`scripts/compare_modes.py`)", "", "| Mode | Pass | Unsafe | Over-cautious | Explanation | p50 ms | Cost (USD) |", "|---|---:|---:|---:|---:|---:|---:|"]
    for name, m in modes["modes"].items():
        L.append(f"| {name} | {pct(m['pass_rate'])} | {m['errors'].get('unsafe_error', 0)} | {m['errors'].get('over_cautious', 0)} | "
                 f"{m['explanation_avg_score']} | {m['latency_p50_ms']} | {m['total_cost_usd']} |")
    L += ["", "Adding the LLM to the rules (`ai`) does not fix the unsafe cases; the policy gate, fallback route and pattern rules of the `graph` do.",
          "The LLM's contribution is the explanation - and template explanations score at least as high (10 vs "
          f"{a['explanation_avg_score']}) on our rubric, at zero cost and latency. LLM prose is kept because it is more readable to a reviewer, not because it scores higher.", "",
          "## 4. Operating profile (100 simulated events, HTTP, live model)", "",
          f"- events {sim['events']}, failed {sim['failed']}, audit recorded {pct(sim['audit_recorded_share'])}",
          f"- latency ms: {sim['latency_ms']}",
          f"- LLM reviewed {pct(sim['llm_reviewed_share'])}, fast path {pct(sim['fast_path_share'])}; with LLM vs without (ms): {sim['latency_llm_vs_no_llm_ms']}",
          f"- cost: {sim['cost']}", f"- decisions {sim['actions']}", f"- injected-scenario checks: {sim['scenario_checks']}", "",
          "## 5. What this does not show", "",
          "- Behaviour on real traffic: all data is synthetic and generated by our own code.",
          "- Statistical confidence: 45 cases (one run, temperature 0) cannot support claims beyond \"no regression on these cases\".",
          "- Model drift: the LLM version can change under us; the eval run should be repeated on every model or prompt change (`scripts/eval_full`).",
          "- Fraud outcomes: nothing here measures money saved or lost, only agreement with our own expected decisions.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    out = settings.base_dir / "docs" / "FINAL_EVALUATION.md"
    out.write_text(build(), encoding="utf8")
    print(f"wrote {out}")
